"""embed-dxbc.py -- the committed DXBC header, and the check that it is current.

  generate HLSL DEF TOOL BLOBDIR COMPILER OUT   write OUT from BLOBDIR/<entry>.dxbc
  check    HLSL DEF TOOL HEADER                 refuse if HEADER was made from other sources

TOOL is the compiler driver's source (tools/shaderc.c), which sets the flags
the blobs were compiled with. The header records the SHA-256 of all three, so
an edit to any of them that was not followed by `make shaders` stops the build
instead of shipping stale code.
"""

from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

ENTRY = re.compile(r'^VGL_SHADER\((\w+),\s*"(\w+)"\)\s*$', re.M)


def digest(path: Path) -> str:
    # Over LF text, so a checkout that converts line endings is still current.
    return hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def generate(hlsl: Path, defs: Path, tool: Path, blobs: Path, compiler: Path,
             out: Path) -> int:
    entries = ENTRY.findall(defs.read_text(encoding="ascii"))
    version = compiler.read_text(encoding="ascii").strip()
    if not entries or not version.startswith("d3dcompiler_47 "):
        print(f"embed-dxbc: nothing to embed ({len(entries)} entries, compiler '{version}')",
              file=sys.stderr)
        return 1
    lines = [
        "/* gpu_shader_dxbc.h -- GENERATED by `make shaders`; do not edit.",
        " *",
        f" * source   {hlsl.as_posix()} sha256 {digest(hlsl)}",
        f" * entries  {defs.as_posix()} sha256 {digest(defs)}",
        f" * driver   {tool.as_posix()} sha256 {digest(tool)}",
        f" * compiler {version}, D3DCOMPILE_OPTIMIZATION_LEVEL3",
        " */",
    ]
    for entry, target in entries:
        data = (blobs / f"{entry}.dxbc").read_bytes()
        lines.append(f"/* {entry}, {target}, {len(data)} bytes */")
        lines.append(f"static const unsigned char vgl_dxbc_{entry}[] = {{")
        for off in range(0, len(data), 16):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[off:off + 16]) + ",")
        lines.append("};")
    lines.append("")
    out.write_text("\n".join(lines), encoding="ascii", newline="\n")
    print(f"embed-dxbc: {len(entries)} shaders from {version} -> {out.as_posix()}")
    return 0


def check(hlsl: Path, defs: Path, tool: Path, header: Path) -> int:
    text = header.read_text(encoding="ascii")
    stale = [p.as_posix() for p in (hlsl, defs, tool)
             if f"{p.as_posix()} sha256 {digest(p)}" not in text]
    if stale:
        print(f"{header.as_posix()} was not generated from the current "
              f"{', '.join(stale)}.\n"
              "Run `make shaders` on Windows (it needs Microsoft's d3dcompiler_47) "
              "and commit the result.", file=sys.stderr)
        return 1
    return 0


def main(argv: list[str]) -> int:
    if len(argv) == 7 and argv[0] == "generate":
        return generate(*map(Path, argv[1:]))
    if len(argv) == 5 and argv[0] == "check":
        return check(*map(Path, argv[1:]))
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
